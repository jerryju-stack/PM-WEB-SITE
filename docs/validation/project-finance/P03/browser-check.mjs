import {createRequire} from 'node:module';
import {homedir} from 'node:os';
import {writeFile,mkdir} from 'node:fs/promises';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const packages=process.env.PLAYWRIGHT_MODULES??join(homedir(),'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules');
const require=createRequire(join(packages,'playwright/package.json'));
const {chromium}=require('playwright');
const folder=dirname(fileURLToPath(import.meta.url));
const base=process.env.P03_BASE||'http://127.0.0.1:18743';
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--no-proxy-server']});
const results=[];
try {
  for(const [device,viewport] of [['desktop',{width:1440,height:1000}],['mobile',{width:390,height:844}]]) {
    const context=await browser.newContext({viewport,hasTouch:device==='mobile'});
    const page=await context.newPage();
    const errors=[],writes=[];
    page.on('pageerror',e=>errors.push(e.message));
    page.on('request',request=>{if(request.url().includes('/api/')&&request.method()!=='GET')writes.push(request.url());});
    const check=(name,condition)=>{assert(condition,device+' / '+name);results.push({device,check:name,status:'passed'});};
    await page.goto(base);
    await page.locator('.finance-project-entry').first().waitFor();
    check('global entry',await page.locator('.finance-prototype-entry').count()===1);
    await page.screenshot({path:join(folder,device+'-website.png'),fullPage:true});
    await page.locator('.finance-prototype-entry').click();
    await page.locator('#project-p03-assembly').click();
    await page.locator('#metric-npv').waitFor();
    check('six metric cards',await page.locator('.fp-metric').count()===6);
    check('three reports and ten module routes',await page.locator('.fp-tabs a').count()===4&&await page.locator('.fp-modules a').count()===10);
    await page.locator('#filter-baseline').selectOption('B00');
    await page.locator('#filter-version').selectOption('F01');
    await page.locator('#filter-period').selectOption('year1');
    await page.locator('#filter-product').selectOption('outboard');
    check('filters in URL',page.url().includes('baseline=B00')&&page.url().includes('version=F01')&&page.url().includes('period=year1')&&page.url().includes('product=outboard'));
    await page.reload();
    await page.locator('#metric-npv').waitFor();
    check('deep link and filters survive refresh',await page.locator('#filter-product').inputValue()==='outboard'&&await page.locator('#filter-period').inputValue()==='year1');
    await page.screenshot({path:join(folder,device+'-dashboard.png'),fullPage:true});
    const metric='#metric-operating_profit';
    await page.locator(metric).scrollIntoViewIfNeeded();
    await page.locator(metric).focus();
    const metricY=await page.evaluate(()=>scrollY);
    await page.locator(metric).click();
    await page.locator('#assembly-link').click();
    await page.locator('#edit-ct').fill('42');
    await page.locator('#preview-change').click();
    check('labor preview direction and amount',(await page.locator('#impact-output').innerText()).includes('-2,000.00'));
    await page.screenshot({path:join(folder,device+'-labor-preview.png'),fullPage:true});
    await page.locator('#fp-back').click();
    await page.locator('#fp-discard').waitFor({state:'visible'});
    await page.screenshot({path:join(folder,device+'-unsaved-return.png')});
    await page.locator('[data-keep]').click();
    check('keep editing preserves input',await page.locator('#edit-ct').inputValue()==='42');
    await page.locator('#fp-back').click();
    await page.locator('[data-discard]').click();
    await page.locator('#assembly-link').waitFor();
    await page.locator('#fp-back').click();
    await page.locator('#metric-npv').waitFor();
    await page.waitForTimeout(100);
    check('return to original metric focus',await page.evaluate(()=>document.activeElement?.id)==='metric-operating_profit');
    check('return to original metric scroll',Math.abs((await page.evaluate(()=>scrollY))-metricY)<3);
    check('filter context preserved across labor route',await page.locator('#filter-product').inputValue()==='outboard');
    await page.goForward();
    await page.locator('#assembly-link').waitFor();
    await page.goBack();
    await page.locator('#metric-npv').waitFor();
    check('browser forward and back',page.url().includes('product=outboard'));

    await page.locator('#dashboard-compare').click();
    await page.locator('#variance-dv-link').scrollIntoViewIfNeeded();
    await page.locator('#variance-dv-link').focus();
    const compareY=await page.evaluate(()=>scrollY);
    await page.locator('#variance-dv-link').click();
    await page.locator('#edit-retest').fill('3000');
    await page.locator('#preview-validation').click();
    check('validation source preview',(await page.locator('#validation-impact').innerText()).includes('-909.09'));
    await page.screenshot({path:join(folder,device+'-validation-preview.png'),fullPage:true});
    await page.goBack();
    await page.locator('#fp-discard').waitFor({state:'visible'});
    await page.locator('[data-keep]').click();
    check('browser back cancellation preserves source',page.url().includes('/validation/dv-01')&&await page.locator('#edit-retest').inputValue()==='3000');
    await page.goBack();
    await page.locator('#fp-discard').waitFor({state:'visible'});
    await page.locator('[data-discard]').click();
    await page.locator('#variance-dv-link').waitFor();
    await page.waitForTimeout(100);
    check('return to original variance focus',await page.evaluate(()=>document.activeElement?.id)==='variance-dv-link');
    check('return to original variance scroll',Math.abs((await page.evaluate(()=>scrollY))-compareY)<3);

    await page.locator('#tab-overview').click();
    const help=page.locator('[data-help="npv"]');
    if(device==='desktop') {
      await help.hover();
      check('mouse hover definition',await page.locator('#fp-tooltip').isVisible());
      await page.mouse.move(0,0);
      await page.locator('#metric-operating_profit').focus();
      await page.keyboard.press('Tab');
      check('keyboard focus definition',await page.locator('#fp-tooltip').isVisible()&&await help.evaluate(e=>e===document.activeElement));
      await page.screenshot({path:join(folder,device+'-definition.png')});
      await page.keyboard.press('Escape');
      check('Escape dismisses and keeps focus',!(await page.locator('#fp-tooltip').isVisible())&&await help.evaluate(e=>e===document.activeElement));
    } else {
      await help.tap();
      check('touch definition',await page.locator('#fp-tooltip').isVisible());
      await page.screenshot({path:join(folder,device+'-definition.png')});
      await page.locator('#close-help').tap();
      check('touch close returns focus',await help.evaluate(e=>e===document.activeElement)&&!(await page.locator('#fp-tooltip').isVisible()));
    }
    for(const section of ['commercial','bom','operations','factory-costs','engineering','prototypes','validation','investment','returns','budget','compare']) {
      const url=base+'/projects/p03-assembly/finance/'+section+'?baseline=B00&version=F01&period=year1&product=outboard';
      const response=await page.goto(url);
      await page.locator('.fp-tabs').waitFor();
      check('direct route '+section,response.status()===200);
      await page.reload();
      await page.locator('.fp-tabs').waitFor();
    }
    await page.locator('#switch-project').click();
    await page.locator('#project-p03-platform').click();
    await page.locator('#metric-npv').waitFor();
    check('switch project',page.url().includes('/p03-platform/finance')&&(await page.locator('h1').innerText()).includes('Dashboard'));
    await page.goto(base+'/#projects');
    await page.locator('a[href="/projects/p03-assembly/finance"]').click();
    await page.locator('#metric-npv').waitFor();
    check('project card direct entry',page.url().includes('/p03-assembly/finance'));
    await page.locator('#metric-operating_profit').click();
    await page.locator('#assembly-link').click();
    await page.locator('#edit-ct').fill('40');
    await page.locator('#save-demo').click();
    await page.reload();
    await page.locator('#edit-ct').waitFor();
    check('browser demo draft survives refresh',await page.locator('#edit-ct').inputValue()==='40');
    await page.locator('#edit-ct').fill('41');
    page.once('dialog',dialog=>dialog.accept());
    await page.reload();
    await page.locator('#edit-ct').waitFor();
    check('reload discards unsaved candidate',await page.locator('#edit-ct').inputValue()==='40');
    await page.goto(base+'/projects/not-visible/finance');
    await page.locator('h1').waitFor();
    check('unavailable project state',(await page.locator('h1').innerText())==='Project unavailable');
    await page.goto(base+'/projects/p03-assembly/finance');
    await page.locator('#metric-npv').waitFor();
    for(const [section,row] of [['operations','assembly-01'],['validation','dv-01']]) {
      await page.goto(base+'/projects/p03-assembly/finance/'+section+'/'+row);
      await page.locator('#fp-back').click();
      await page.waitForURL('**/finance/'+section+'?**');
      check('direct source fallback '+section,!page.url().includes('/'+row));
    }
    await page.goto(base+'/projects/p03-assembly/finance');
    await page.locator('#metric-npv').waitFor();
    check('sample marker visible',await page.locator('.fp-badge').isVisible());
    check('no horizontal page overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    check('no application writes during prototype',writes.length===0);
    check('no JavaScript errors',errors.length===0);
    await context.close();
  }
  await writeFile(join(folder,'browser-checks.json'),JSON.stringify({base,version:'P03-A-en-v1',results},null,2)+'\n');
} finally { await browser.close(); }
